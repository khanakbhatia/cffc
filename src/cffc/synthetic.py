def _write_gz(path: Path, records: List[Dict[str, Any]]) -> None:
    payload = json.dumps(
        {"_synthetic_notice": NOTICE, "Records": records},
        separators=(",", ":"),
    ).encode()

    # Write a deterministic gzip header across Python/platform versions.
    # mtime=0 avoids timestamps; filename="" avoids embedding a path.
    with path.open("wb") as raw:
        with gzip.GzipFile(fileobj=raw, mode="wb", filename="", mtime=0) as gz:
            gz.write(payload)


def generate_synthetic_dataset(root, seed: int = SEED) -> Dict[str, Any]:
    """(Re)generate the synthetic dataset under ``root``. Refuses to touch a 'real' data root."""
    root = Path(root)
    prov = root / "PROVENANCE.json"
    if prov.exists():
        kind = json.loads(prov.read_text()).get("kind")
        if kind != "synthetic":
            raise RuntimeError(f"{root} is marked {kind!r}; refusing to write synthetic data into it")
    for sub in ("raw", "ground_truth", "manifests"):
        d = root / sub
        if d.exists():
            for p in d.rglob("*"):
                if p.is_file():
                    os.chmod(p, 0o644)
            shutil.rmtree(d)
        d.mkdir(parents=True)
    prov.write_text(json.dumps({"kind": "synthetic", "notice": NOTICE, "generator": "cffc.synthetic", "seed": seed},
                               indent=2) + "\n")
    summary: Dict[str, Any] = {}
    for sc, (base, builder) in SCENARIOS.items():
        rng = random.Random(f"{seed}:{sc}")
        recs, steps, groups = builder(base, rng)
        rng.shuffle(recs)  # delivery order inside a file is not chronological
        half = len(recs) // 2
        parts = [recs[:half], recs[half:]]
        raw_dir = root / "raw" / sc
        raw_dir.mkdir(parents=True)
        for k, part in enumerate(parts):
            t0 = min(r["eventTime"] for r in part).replace("-", "").replace(":", "")[:13] + "Z"
            suffix = uuid.uuid5(_NS, f"{sc}:{k}").hex[:16].upper()
            _write_gz(raw_dir / f"{ACCOUNT}_CloudTrail_{REGION}_{t0}_{suffix}.json.gz", part)
        gt = {"schema_version": "1.0", "scenario": sc, "created_at_utc": format_utc(base - timedelta(minutes=5)),
              "author": "synthetic-generator", "frozen": True, "synthetic": True, "steps": steps,
              "expected_correlation_groups": [{"group_id": g, "member_step_ids": m, "rationale": r} for g, m, r in groups]}
        gt_path = root / "ground_truth" / f"{sc}_ground_truth.json"
        gt_path.write_text(json.dumps(gt, indent=2) + "\n")
        os.chmod(gt_path, 0o444)
        integrity.build_manifest_for_directory(root / "raw", sc, root / "manifests" / f"{sc}_manifest.json",
                                               "synthetic-generator", collected_at_utc=format_utc(base + timedelta(hours=1)))
        summary[sc] = {"records": len(recs), "steps": len(steps)}
    return summary
